// 1) Сцены-диалоги: когда открывается глава, герои говорят с Валерой (несколько реплик и иногда выбор —
//    он влияет на настроение и мелкие бонусы, но не на сложность). Сцену можно пролистать.
// 2) Новые лёгкие главы между старыми: метро, письмо Михалыча, «кто-то следит» и по одной на путь.
// 3) К финалу — звонки «из службы безопасности банка»: завязка переезда в Мексику (mex.js).
// Система сцен общая: Мексика добавляет свои сцены в STORY_SCENES.

const STORY_SCENES = {};

function storyScene(qid) { return STORY_SCENES[qid]; }
function storySeen() { if (!S.storyScenes) S.storyScenes = {}; return S.storyScenes; }
let SCENE_RUN = null;
function playStoryScene(qid, force) {
  const sc = storyScene(qid);
  if (!sc || (!force && storySeen()[qid])) return;
  storySeen()[qid] = Date.now();
  SCENE_RUN = { qid, i: 0, sc };
  storySceneDraw();
}
function storySceneDraw() {
  const r = SCENE_RUN;
  if (!r) return;
  const line = r.sc.lines[r.i];
  const last = r.i >= r.sc.lines.length - 1;
  const choices = last && r.sc.choices ? r.sc.choices : null;
  openModal(`<div class="st-scene">
      <div class="st-who"><span>${line[0]}</span><b>${esc(line[1])}</b></div>
      <div class="st-text">${line[2]}</div>
      <div class="st-dots">${r.sc.lines.map((_, i) => `<i class="${i === r.i ? 'on' : ''}"></i>`).join('')}</div>
      ${choices ? `<div class="btns" style="flex-direction:column;gap:8px">${choices.map((c, i) => `<button class="btn ${i ? '' : 'primary'} wide" data-act="stChoice" data-id="${i}">${c.label}</button>`).join('')}</div>`
        : `<div class="btns"><button class="btn primary wide" data-act="stNext">${last ? 'Понятно' : 'Дальше ›'}</button>${!last ? '<button class="btn small" data-act="stSkip">Пропустить</button>' : ''}</div>`}
    </div>`, { center: true });
}
Object.assign(ACTIONS, {
  stNext: () => { const r = SCENE_RUN; if (!r) return; if (r.i >= r.sc.lines.length - 1) { SCENE_RUN = null; closeModal(); return; } r.i++; sfx('click'); storySceneDraw(); },
  stSkip: () => { const r = SCENE_RUN; if (!r) return; r.i = r.sc.lines.length - 1; storySceneDraw(); },
  stChoice: (i) => {
    const r = SCENE_RUN;
    if (!r || !r.sc.choices) return;
    const c = r.sc.choices[+i];
    SCENE_RUN = null;
    closeModal();
    const res = c.run ? c.run() : '';
    if (!S.storyPicks) S.storyPicks = {};
    S.storyPicks[r.qid] = +i;
    if (res) setTimeout(() => toast(res, 'good'), 200);
    save();
  },
  stReplay: (qid) => playStoryScene(qid, true),
});
// Глава открылась — показать её сцену (в очереди окон, после окна награды)
HOOKS.tick.push(() => {
  if (!S.storySeen || (S.tut && !S.tut.done) || typeof currentQuest !== 'function') return;
  const q = currentQuest();
  if (!q || !storyScene(q.id) || storySeen()[q.id]) return;
  if (popupTurn(2)) playStoryScene(q.id);
});
// В карточке главы — кнопка «пересмотреть разговор»
const _storyTabScenes = EXTRA_TABS.tasks.story;
EXTRA_TABS.tasks.story = () => {
  const html = _storyTabScenes();
  const q = currentQuest();
  return q && storyScene(q.id) ? html.replace('<div class="q-reward">', `<button class="btn small st-replay" data-act="stReplay" data-id="${q.id}">💬 Разговор</button><div class="q-reward">`) : html;
};

