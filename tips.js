function showTip(key, force) {
  const t = TIPS[key];
  if (!t) return;
  if (!S.tipsSeen) S.tipsSeen = {};
  if (S.tipsSeen[key] && !force) return;
  S.tipsSeen[key] = 1;
  openModal(`<div class="tip"><div class="tip-e">${t.e}</div><h3>${t.t}</h3><ul>${t.l.map((x) => `<li>${x}</li>`).join('')}</ul>
    <div class="btns"><button class="btn primary wide" data-act="close">Понятно</button></div></div>`, { center: true });
}

function tipsReady() { return S.storySeen && S.tut && S.tut.done && !modalOpen(); }

